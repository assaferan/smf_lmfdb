"""
Update the database to omf5_data with the Hecke rings recomputed, and with the
eigenvalues of the paramodular non-lifts of dimension 14-20.

omf5's parse_omf5 stored the ring of integers as the Hecke ring, with index 1 and
nbound 0, whenever the Z-span of the first few lambda_p had rank less than the
degree (always for degree >= 6).  omf5_data now has, for every orbit with
eigenvalue coordinates, the order generated by its eigenvalues, its index in the
ring of integers, and nbound; and has coordinates for the orbits of dimension
14-20, which it did not have before.  For weight (3,0) this script:

  orbits with an smf_hecke_nf row (dimension <= 13):
    smf_hecke_nf:  the Hecke ring basis and the coordinates in it (lambda_p,
                   lambda_p_square, an), where the Hecke ring changed;
    smf_newforms:  hecke_ring_generator_nbound and hecke_ring_index_factorization;

  orbits of dimension 14-20 (no smf_hecke_nf row before):
    smf_hecke_nf:  inserts a row;
    smf_newforms:  traces (the whole Dirichlet series; before, only a_1, a_p and
                   a_{p^2}), field_disc, field_disc_factorization, nf_label,
                   hecke_ring_generator_nbound and hecke_ring_index_factorization.

Checks, before writing:
  - each orbit of omf5_data with coordinates is a single stored smf_newforms row,
    and every stored smf_hecke_nf row of a G orbit of weight (3,0) is one of them;
  - the stored nbound and index factorization are those of the previous omf5_data
    (--old-rev), so the rows come from it;
  - an existing smf_hecke_nf row differs from the regenerated one only in the Hecke
    ring basis and coordinates, and the old and new coordinates are the same
    elements of the field (lambda_p, lambda_p_square, an);
  - for the new orbits, as in add_g_hecke_nf: the regeneration agrees with the
    stored row in every other column, the new traces agree with the stored ones
    where those are not NULL, and the traces of `an` are the new traces.

Usage (from the lmfdb root, with write access to the db; omf5_data at the new commit):
    sage -python -m smf_lmfdb.db_tables.update_hecke_rings [--datafile PREFIX] [--procs N] [--old-rev REV]          # dry run
    sage -python -m smf_lmfdb.db_tables.update_hecke_rings [--datafile PREFIX] [--procs N] [--old-rev REV] --apply
"""
import argparse
import json
import os
import re
import subprocess
import sys
import time
from collections import Counter
from multiprocessing import Pool

from sage.all import factor

from lmfdb import db
from smf_lmfdb.db_tables.common_populate import common_entry_values
from smf_lmfdb.db_tables.fix_sk_traces import write_update_file
from smf_lmfdb.db_tables.fix_sk_invalid_lifts import jsonable
from smf_lmfdb.db_tables.nf_elt import get_nf_basis, nf_lists_to_elements
from smf_lmfdb.db_tables.smf_hecke_nf_populate import entry_add_columns as hnf_add_columns
from smf_lmfdb.Hecke_Eigenvalues.paramodular.Hecke_Eigenvalues_paramodular import (
    Hecke_Eigenforms_paramodular, Hecke_Eigenvalues_paramodular_G, parse_omf5)
from smf_lmfdb.Hecke_Eigenvalues.paramodular.omf5_squares import OMF5_DIR

K, J = 3, 0
MIN_NEW, MAX_NEW = 14, 20
# the previous omf5_data (the commit the database was populated from)
OLD_REV = "5693c84a"
NF_COLS = ['traces', 'field_disc', 'field_disc_factorization', 'nf_label', 'hecke_ring_generator_nbound',
           'hecke_ring_index_factorization']
# the columns of smf_newforms that change for the orbits already in smf_hecke_nf
NF_RING_COLS = ['hecke_ring_generator_nbound', 'hecke_ring_index_factorization']
# the columns of smf_hecke_nf that change with the Hecke ring
HNF_RING_COLS = ['hecke_ring_numerators', 'hecke_ring_denominators', 'hecke_ring_inverse_numerators',
                 'hecke_ring_inverse_denominators', 'lambda_p', 'lambda_p_square', 'an']
# the columns of smf_hecke_nf holding coordinates, compared as field elements
COORD_COLS = ['lambda_p', 'lambda_p_square', 'an']
# columns of smf_newforms the generator does not make (set by the populate script or later fixes)
NOT_COMPARED = {'id', 'label', 'hecke_orbit', 'hecke_orbit_code', 'space_label', 'multiplicity', 'related_objects',
                'embedded_related_objects', 'trace_hash', 'analytic_rank', 'analytic_rank_proved', 'qexp_display',
                'fricke_eigenval', 'trace_display'}


def nulls(x):
    if isinstance(x, list):
        return [nulls(y) for y in x]
    return None if x == 'NULL' else x


def index_factorization(index):
    return [[int(p), int(e)] for p, e in factor(index)]


def old_forms(N, rev):
    """The G orbits with coordinates in omf5_data at the commit rev."""
    path = "hecke_evs_3_0/data/hecke_ev_%d_%d_%d.dat" % (K, J, N)
    r = subprocess.run(['git', '-C', OMF5_DIR, 'show', '%s:%s' % (rev, path)], capture_output=True, text=True)
    if r.returncode != 0:
        return []
    forms = eval(re.sub(r'(\d)L', r'\1', r.stdout))
    return [f for f in forms if f['aut_rep_type'] == 'G' and f.get('lambda_p')]


def key(f):
    # (twin orbits can share the signs, dimension and traces, e.g. at level 748; not the field_poly)
    return (f['atkin_lehner_string'], tuple(int(c) for c in f['field_poly']), tuple(nulls(f['trace_lambda_p'])))


def level_data(args):
    """Database-free: the new and old omf5_data orbits with coordinates, and their smf_hecke_nf entries."""
    N, rev = args
    t = time.time()
    raw = [f for f in parse_omf5(K, J, N) if f['aut_rep_type'] == 'G' and f.get('lambda_p')]
    old = {key(f): f for f in old_forms(N, rev)}
    assert len({key(f) for f in raw}) == len(raw), "level %d: two orbits with the same key" % N
    assert len(old) == len(old_forms(N, rev)), "level %d: two old orbits with the same key" % N
    evs = [e for e in Hecke_Eigenvalues_paramodular_G(K, J, N) if 'hecke_ring_numerators' in e]
    out = []
    for f in raw:
        m = [e for e in evs if e['field_poly'] == f['field_poly'] and e['trace_lambda_p'] == f['trace_lambda_p']]
        assert len(m) == 1, "level %d: %d smf_hecke_nf entries for an orbit" % (N, len(m))
        e = common_entry_values(K, J, N, 'K')
        e.update(m[0])
        e = hnf_add_columns(e, {'id': None, 'num_forms': 1})     # computes an; the label is set later
        out.append((f, old.get(key(f)), e))
    print("level %d: %d orbits (%.0fs)" % (N, len(out), time.time() - t), file=sys.stderr, flush=True)
    return N, out


def elements(h, cols):
    basis, _ = get_nf_basis(h)
    return {c: nf_lists_to_elements(['NULL' if v is None else v for v in h[c]], basis) for c in cols if h.get(c)}


def levels():
    folder = os.path.join(OMF5_DIR, "hecke_evs_3_0", "data")
    return sorted(int(m.group(1)) for m in (re.match(r"hecke_ev_3_0_(\d+)\.dat$", fn) for fn in os.listdir(folder)) if m)


def main(apply=False, datafile=None, procs=8, only=None, rev=OLD_REV):
    ls = only or levels()
    print("%d levels" % len(ls))
    nf_cols = db.smf_newforms.search_cols
    hnf_cols = db.smf_hecke_nf.search_cols
    with Pool(procs) as pool:
        data = dict(pool.imap_unordered(level_data, [(N, rev) for N in ls]))
    nf_ring, nf_out, hnf_upd, hnf_new, stats = [], [], [], [], Counter()
    for N in sorted(data):
        stored = list(db.smf_newforms.search({'family': 'K', 'level': N, 'weight': [K, J], 'aut_rep_type': 'G'},
                                             ['id'] + nf_cols))
        stored_hnf = {h['label']: h for h in db.smf_hecke_nf.search(
            {'label': {'$in': [r['label'] for r in stored]}}, ['id'] + hnf_cols)}
        seen = set()
        new_forms = None
        for f, old, e in data[N]:
            dim = len(f['field_poly']) - 1
            m = [r for r in stored if r['dim'] == dim and r['field_poly'] and key(r) == key(f)]
            assert len(m) == 1, "level %d: %d stored rows for an orbit" % (N, len(m))
            r = m[0]
            seen.add(r['label'])
            e.pop('label')
            e = hnf_add_columns(e, {'id': None, 'num_forms': r['hecke_orbit']})
            assert (e['label'], e['hecke_orbit_code']) == (r['label'], r['hecke_orbit_code']), r['label']
            # (smf_hecke_nf keeps the 'NULL' strings of omf5_data in its coordinate lists)
            h = {c: e.get(c) for c in hnf_cols}
            nbound = int(f['hecke_ring_generator_nbound'])
            index_fac = index_factorization(f['hecke_ring_index'])

            if r['label'] in stored_hnf:
                # an orbit already in smf_hecke_nf: only the Hecke ring changes
                s = stored_hnf[r['label']]
                assert old is not None, "%s: not in the previous omf5_data" % r['label']
                assert r['hecke_ring_generator_nbound'] == old['hecke_ring_generator_nbound'], r['label']
                assert jsonable(r['hecke_ring_index_factorization']) == index_factorization(old['hecke_ring_index']), r['label']
                diff = [c for c in hnf_cols if jsonable(h.get(c)) != jsonable(s.get(c))]
                assert set(diff) <= set(HNF_RING_COLS), "%s: smf_hecke_nf differs in %s" % (r['label'], diff)
                if diff:
                    old_elts, new_elts = elements(s, COORD_COLS), elements(h, COORD_COLS)
                    assert old_elts.keys() == new_elts.keys(), r['label']
                    for c in old_elts:
                        assert old_elts[c] == new_elts[c], "%s: %s are not the same field elements" % (r['label'], c)
                    hnf_upd.append(dict({'id': s['id']}, **{c: jsonable(h[c]) for c in HNF_RING_COLS}))
                    stats['smf_hecke_nf rows rewritten'] += 1
                if (nbound, index_fac) != (r['hecke_ring_generator_nbound'], jsonable(r['hecke_ring_index_factorization'])):
                    nf_ring.append({'id': r['id'], 'hecke_ring_generator_nbound': nbound,
                                    'hecke_ring_index_factorization': index_fac})
                    stats['index changed' if index_fac != jsonable(r['hecke_ring_index_factorization']) else 'nbound only'] += 1
                continue

            # a new orbit (dimension 14-20)
            assert MIN_NEW <= dim <= MAX_NEW and old is None, "%s: no smf_hecke_nf row" % r['label']
            assert db.smf_hecke_nf.count({'label': r['label']}) == 0, r['label']
            if new_forms is None:
                new_forms = [g for g in Hecke_Eigenforms_paramodular(K, J, N)
                             if g.get('aut_rep_type') == 'G' and MIN_NEW <= g['dim'] <= MAX_NEW and 'hecke_ring_index' in g]
            g = [g for g in new_forms if key(g) == key(f)]
            assert len(g) == 1, "%s: %d regenerated rows" % (r['label'], len(g))
            g = g[0]
            diff = [c for c in nf_cols if c in g and c not in NOT_COMPARED and c not in NF_COLS
                    and jsonable(nulls(g[c])) != jsonable(r.get(c))]
            assert not diff, "%s: the regeneration differs in %s" % (r['label'], diff)
            new, old_tr = nulls(g['traces']), r['traces']
            assert len(new) == len(old_tr), r['label']
            for n, (a, b) in enumerate(zip(old_tr, new), 1):
                assert b is not None or a is None, "%s: a_%d would become NULL" % (r['label'], n)
                assert a is None or a == b, "%s: a_%d = %s stored, %s from the coordinates" % (r['label'], n, a, b)
            stats['traces filled in'] += sum(1 for a, b in zip(old_tr, new) if a is None and b is not None)
            basis, _ = get_nf_basis(h)
            an = nf_lists_to_elements(h['an'], basis)
            assert [None if a == 'NULL' else int(a.trace()) for a in an] == new[:len(an)], r['label']
            row = {'id': r['id']}
            for c in NF_COLS:
                row[c] = jsonable(nulls(g.get(c)))
            assert row['hecke_ring_generator_nbound'] == nbound and row['hecke_ring_index_factorization'] == index_fac
            nf_out.append(row)
            hnf_new.append(h)
            stats['new orbits'] += 1
            stats['new orbits with field_disc'] += row['field_disc'] is not None
        # every stored smf_hecke_nf row of a G orbit of this level was checked
        assert set(stored_hnf) <= seen, "level %d: smf_hecke_nf rows not in omf5_data: %s" % (N, set(stored_hnf) - seen)
        stats['orbits'] += len(data[N])
    print(dict(stats))
    prefix = datafile or "smf_hecke_rings"
    write_update_file(prefix + "_newforms_ring.txt", db.smf_newforms, 'id', nf_ring, NF_RING_COLS)
    write_update_file(prefix + "_newforms_new.txt", db.smf_newforms, 'id', nf_out, NF_COLS)
    write_update_file(prefix + "_hecke_nf.txt", db.smf_hecke_nf, 'id', hnf_upd, HNF_RING_COLS)
    with open(prefix + "_hecke_nf_new.json", "w") as F:
        json.dump(jsonable(hnf_new), F)
    print("wrote %s_newforms_ring.txt (%d rows), %s_newforms_new.txt (%d rows), %s_hecke_nf.txt (%d rows), "
          "%s_hecke_nf_new.json (%d rows)" % (prefix, len(nf_ring), prefix, len(nf_out), prefix, len(hnf_upd),
                                              prefix, len(hnf_new)))
    if not apply:
        print("dry run; pass --apply to write")
        return
    # update_from_file builds a replacement table (undo with reload_revert()); the new
    # smf_hecke_nf rows can be removed by label
    db.smf_newforms.update_from_file(prefix + "_newforms_ring.txt", label_col='id')
    if nf_out:
        db.smf_newforms.update_from_file(prefix + "_newforms_new.txt", label_col='id')
    db.smf_hecke_nf.update_from_file(prefix + "_hecke_nf.txt", label_col='id')
    if hnf_new:
        db.smf_hecke_nf.insert_many(jsonable(hnf_new))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--apply', action='store_true')
    parser.add_argument('--datafile')
    parser.add_argument('--procs', type=int, default=8)
    parser.add_argument('--levels', help="comma-separated levels (default: all)")
    parser.add_argument('--old-rev', default=OLD_REV, help="the omf5_data commit the database was populated from")
    args = parser.parse_args()
    only = [int(x) for x in args.levels.split(',')] if args.levels else None
    main(apply=args.apply, datafile=args.datafile, procs=args.procs, only=only, rev=args.old_rev)
