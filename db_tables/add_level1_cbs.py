"""
Add the general-type forms of level 1 and weight (k, j), j > 0, computed with
CovariantsBinarySextics (assaferan/CovariantsBinarySextics, scripts/SiegelModularForms.py).

The spaces 2.{K,P,S}.1.k.j.a store their Klingen-Eisenstein lifts (type Q) but no
form of general type.  For each space DATADIR/k_j holds
  dec_k_j.in   the Hecke decomposition of M_{k,j}(Sp(4,Z)) (SMF(k, j).HeckeDecomposition,
               WriteDecompositionToFile): its eigenforms, each with its Hecke field;
  ev_q.out     hecke_eigenvalues.exe q on it: for each eigenform y = the eigenvalue of
               T(p) (q = p) or T_1(p^2) (q = p^2) as [Tr(y), Tr(xy), ..., Tr(x^(d-1) y)],
               x the generator of the field.
From these, at each prime p (all p are good):
  lambda_p          = T(p);
  lambda_p_square_1 = T_1(p^2), lambda_p_square_2 = p^(2k+j-6),
  lambda_p_square_0 = lambda_p^2 - (p+1) lambda_p_square_1 - (p^2+1)(p+1) lambda_p_square_2,
  lambda_p_square   = T(p^2) = lambda_p_square_0 + lambda_p_square_1 + lambda_p_square_2
(the identities hold for the stored Klingen-Eisenstein rows), and the Dirichlet
coefficients a_n, n <= 100, of the spin L-function, as Get_All_Dirichlet_Coeffs_Up_To.

Each eigenform of the decomposition is either a stored Q row (same dimension and
traces of lambda_p at every computed prime) or of general type.  Before writing
anything it checks, in each space:
  - that every stored Q row is exactly one eigenform;
  - that the dimensions of the others add up to new_cusp_G_dim;
  - that the stored Q rows are numbered 1, ..., nQ, so the new G rows (numbered
    after them by (dim, trace_lambda_p), as the types F, Q, P, Y, G) relabel nothing.
The Hecke ring of a G orbit is the order generated by its lambda_p, lambda_p_square and
lambda_p_square_1 (index, nbound, basis as omf5_data's add_coordinates_14_20.orbit_data); when disc(H)
cannot be factored the field and index columns are left NULL.  As for the stored orbits
(and omf5_data), an orbit of degree > 20 gets neither a Hecke ring nor an smf_hecke_nf
row: only its field polynomial and traces.

New rows for each of the families K, P, S (level 1 is stored in all three); a
space whose forms are then all stored gets num_forms.

Usage (from the lmfdb root, with write access to the db):
    sage -python -m smf_lmfdb.db_tables.add_level1_cbs DATADIR [--datafile PREFIX] [--spaces k_j,...]          # dry run
    sage -python -m smf_lmfdb.db_tables.add_level1_cbs DATADIR [--datafile PREFIX] --apply
"""
import argparse
import json
import os
import re
import sys
import time

from sage.all import (Matrix, NumberField, PolynomialRing, PowerSeriesRing, QQ, ZZ, factor, lcm, pari,
                      prime_range, vector)

from lmfdb import db
from smf_lmfdb.db_tables.common_populate import base_26, common_entry_values, entry_add_common_columns, make_space_label
from smf_lmfdb.db_tables.fix_sk_invalid_lifts import jsonable
from smf_lmfdb.db_tables.add_level2_lifts import make_orbit_code, nulls, sort_key

FAMILIES = 'KPS'
PRIMES = prime_range(100)
SQUARES = [p for p in PRIMES if p * p < 100]
NUM_COEFFS = 100
HECKE_TYPES = ['lambda_p', 'lambda_p_square', 'lambda_p_square_0', 'lambda_p_square_1', 'lambda_p_square_2']
MAX_DISC_DIGITS = 120     # disc(H) is factored (and the field columns filled) up to this size
MAX_RING_DEGREE = 20      # no Hecke ring and no smf_hecke_nf row above this degree


# ---------- reading the CovariantsBinarySextics output ----------

def read_eigenvalues(fname):
    """[(field_poly, [Tr(y), Tr(xy), ...])] in the order of the eigenforms."""
    out = []
    for block in open(fname).read().strip().split('\n\n'):
        lines = block.strip().split('\n')
        assert lines[1].startswith('Total number'), fname
        out.append((lines[2].strip(), [ZZ(t) for t in lines[3:]]))
    return out


def element(F, traces):
    """The y in F with Tr(x^i y) = traces[i], x = F.gen()."""
    d = F.degree()
    x = F.gen()
    pw = [x**i for i in range(2 * d - 1)]
    M = Matrix(QQ, d, d, lambda i, m: pw[i + m].trace())
    c = M.solve_right(vector(QQ, traces))
    return F(list(c))


def eigenforms(datadir, k, j):
    """[(F, {q: eigenvalue})] for the eigenforms of SMF(k, j), q over the computed p and p^2."""
    d = os.path.join(datadir, '%d_%d' % (k, j))
    qs = sorted(int(re.match(r'ev_(\d+)\.out$', f).group(1)) for f in os.listdir(d) if re.match(r'ev_\d+\.out$', f))
    R = PolynomialRing(QQ, 'x')
    forms = None
    for q in qs:
        ev = read_eigenvalues(os.path.join(d, 'ev_%d.out' % q))
        if forms is None:
            forms = [(NumberField(R(pol), 'nu'), {}) for pol, _ in ev]     # also of degree 1
        assert len(ev) == len(forms), (k, j, q)
        for (F, vals), (pol, tr) in zip(forms, ev):
            assert R(pol) == F.defining_polynomial(), (k, j, q)
            vals[q] = element(F, tr)
    return forms or []


# ---------- eigenvalues ----------

def computed_primes(vals):
    """The primes p < 100 with T(p) computed, in order, up to the first missing one; and those p with T_1(p^2)."""
    ps = []
    for p in PRIMES:
        if p not in vals:
            break
        ps.append(p)
    sq = []
    for p in SQUARES:
        if p * p not in vals:
            break
        sq.append(p)
    return ps, sq


def hecke_values(k, j, vals, ps, sq):
    ev = {'lambda_p': [vals[p] for p in ps]}
    for t in HECKE_TYPES[1:]:
        ev[t] = []
    for p in sq:
        l1 = vals[p * p]
        l2 = ZZ(p)**(2*k + j - 6)
        l0 = vals[p]**2 - (p + 1) * l1 - (p*p + 1) * (p + 1) * l2
        ev['lambda_p_square_0'].append(l0)
        ev['lambda_p_square_1'].append(l1)
        ev['lambda_p_square_2'].append(l0.parent()(l2))
        ev['lambda_p_square'].append(l0 + l1 + l2)
    return ev


def dirichlet(k, j, ap, ap2, ps, length=NUM_COEFFS):
    """a_1, ..., a_length of the spin L-function, with Euler factor 1/Q_p(p^-s),
    Q_p(t) = 1 - l_p t + (l_p^2 - l_(p^2) - p^(mu-1)) t^2 - p^mu l_p t^3 + p^(2 mu) t^4, mu = j + 2k - 3,
    as the stored smf_newforms.traces of level 1 (so a_(p^2) = l_(p^2) + p^(mu-1));
    None where a needed eigenvalue is not computed."""
    mu = j + 2*k - 3
    lam = dict(zip(ps, ap))
    lam2 = dict(zip(ps, ap2))
    one = ap[0].parent()(1)
    a = [None, one]
    for n in range(2, length + 1):
        fac = factor(n)
        if len(fac) > 1:
            m = fac[0][0]**fac[0][1]
            a.append(None if a[m] is None or a[n // m] is None else a[m] * a[n // m])
            continue
        p, r = fac[0]
        if p not in lam:
            a.append(None)
        elif r == 1:
            a.append(lam[p])
        elif p not in lam2:
            a.append(None)
        else:
            R = PowerSeriesRing(one.parent(), 't', default_prec=r + 1)
            t = R.gen()
            Q = 1 - lam[p] * t + (lam[p]**2 - lam2[p] - p**(mu - 1)) * t**2 - p**mu * lam[p] * t**3 + p**(2*mu) * t**4
            a.append((1 / Q)[r])     # .list() drops trailing zeros
    return a[1:]


def trace(x, F):
    return ZZ(F(x).trace())


# ---------- the Hecke ring (as omf5_data/add_coordinates_14_20.py) ----------

def _hnf(rs):
    D = lcm([c.denominator() for r in rs for c in r])
    M = (Matrix(QQ, rs) * D).change_ring(ZZ).echelon_form()
    return [vector(QQ, r) / D for r in M.rows() if r]


def ring_closure(F, gens, M=None):
    """Rows over QQ (power basis) of a Z-basis of the ring generated by the elements gens (and,
    if given, the Z-module M containing 1): the smallest module containing 1 and M and closed
    under multiplication by each generator."""
    gens = [F(list(g)) for g in gens]
    M = _hnf([vector(QQ, list(F(1)))] + list(M or []) + [vector(QQ, list(g)) for g in gens])
    while True:
        els = [F(list(r)) for r in M]
        new = _hnf(M + [vector(QQ, list(g * e)) for g in gens for e in els])
        if new == M:
            return M
        M = new


def triangular(rows):
    d = len(rows)
    D = lcm([c.denominator() for r in rows for c in r])
    M = Matrix(ZZ, [[ZZ(c * D) for c in reversed(list(r))] for r in rows]).echelon_form()
    out = [vector(QQ, list(reversed(list(r)))) / D for r in reversed(M.rows())]
    assert out[0] == vector(QQ, [1] + [0] * (d - 1))
    return out


def disc(F, rows):
    els = [F(list(r)) for r in rows]
    return ZZ(Matrix(QQ, [[(x * y).trace() for y in els] for x in els]).det())


def ring_data(F, gens):
    """The smf_hecke_nf basis columns and the smf_newforms field and index columns of the order
    generated by gens = [(j, eigenvalue)] (j = p or p^2, in increasing order)."""
    d = F.degree()
    H = ring_closure(F, [x for _, x in gens])
    assert len(H) == d, "the eigenvalues do not generate an order"
    # nbound: the smallest n such that the eigenvalues indexed by j <= n generate H
    nbound, M, used = 1, ring_closure(F, []), []
    for jj, x in gens:
        if M == H:
            break
        used.append(x)
        M = ring_closure(F, used, M)
        nbound = jj
    # a basis starting with 1, as the pages expect (1, beta_1, ..., beta_{d-1})
    mat = Matrix(QQ, triangular(H))
    inv = mat**(-1)
    ring = {'hecke_ring_power_basis': False, 'hecke_ring_cyclotomic_generator': 0, 'hecke_ring_rank': d,
            'field_poly': [int(c) for c in F.defining_polynomial().list()],
            'hecke_ring_denominators': [int(r.denominator()) for r in mat],
            'hecke_ring_numerators': [[int(c) for c in r.denominator() * r] for r in mat],
            'hecke_ring_inverse_denominators': [int(r.denominator()) for r in inv],
            'hecke_ring_inverse_numerators': [[int(c) for c in r.denominator() * r] for r in inv]}
    fields = {'dim': d, 'relative_dim': d, 'field_poly': ring['field_poly'], 'hecke_ring_generator_nbound': int(nbound),
              'field_poly_is_cyclotomic': False, 'field_poly_root_of_unity': 0, 'field_poly_is_real_cyclotomic': False}
    dH = disc(F, H)
    fields.update({'hecke_ring_index': None, 'hecke_ring_index_proved': False, 'hecke_ring_index_factorization': None,
                   'field_disc': None, 'field_disc_factorization': None, 'nf_label': None, 'is_polredabs': None})
    if len(str(abs(dH))) <= MAX_DISC_DIGITS:
        fac = [(ZZ(p), int(e)) for p, e in abs(dH).factor(proof=False)]
        if all(p.is_prime(proof=True) for p, _ in fac):
            P = [int(p) for p, e in fac if e >= 2]
            pol = F.polynomial()
            if P:
                O1 = [vector(QQ, [QQ(c) for c in pari(b).Vecrev()] + [0] * (d - len(pari(b).Vecrev())))
                      for b in pari.nfbasis([pari(pol), P])]
                OK = _hnf(O1 + H)     # nfbasis is an order containing H's index-prime parts: their sum
                OK = ring_closure(F, [F(list(r)) for r in OK], OK)
            else:
                OK = H
            dK = disc(F, OK)
            index = ZZ((dH / dK).sqrt())
            assert index**2 * dK == dH
            nf = pari.nfinit([pari(pol), pari([pari(F(list(r)).polynomial()) for r in triangular(OK)])])
            assert ZZ(pari('(x) -> x.disc')(nf)) == dK
            red = [int(c) for c in pari(pari.polredabs(nf)).Vecrev()]
            fdisc = [[int(p), int(dK.valuation(p))] for p, _ in fac if dK.valuation(p)]
            fields.update({'hecke_ring_index': int(index), 'hecke_ring_index_proved': True,
                           'hecke_ring_index_factorization': [[int(p), int(e)] for p, e in index.factor()],
                           'field_disc': int(dK), 'field_disc_factorization': ([[-1, 1]] if dK < 0 else []) + fdisc,
                           'nf_label': db.nf_fields.lucky({'coeffs': red}, 'label'),
                           'is_polredabs': red == fields['field_poly']})
    return ring, fields


def coords(ring, F):
    inv = Matrix(QQ, [[QQ(c) / den for c in nums] for nums, den in
                      zip(ring['hecke_ring_inverse_numerators'], ring['hecke_ring_inverse_denominators'])])
    def c(x):
        if x is None:
            return None
        v = vector(QQ, list(F(x))) * inv
        assert all(t in ZZ for t in v), "an eigenvalue is not in the Hecke ring"
        return [int(t) for t in v]
    return c


# ---------- the rows ----------

def g_orbit(k, j, F, vals):
    """The smf_newforms fields (without labels) and smf_hecke_nf fields of one G orbit."""
    ps, sq = computed_primes(vals)
    ev = hecke_values(k, j, vals, ps, sq)
    an = dirichlet(k, j, ev['lambda_p'], ev['lambda_p_square'], ps)
    row = {'trace_' + t: [trace(x, F) for x in ev[t]] for t in HECKE_TYPES}
    row['traces'] = [None if x is None else trace(x, F) for x in an]
    row['trace_display'] = row['trace_lambda_p'][:4]
    # T(p) and T_1(p^2) generate the Hecke algebra; T(p^2) and T_0(p^2) are polynomials in them
    gens = sorted([(p, x) for p, x in zip(ps, ev['lambda_p'])] +
                  [(p * p, x) for p, x in zip(sq, ev['lambda_p_square_1'])] +
                  [(p * p, x) for p, x in zip(sq, ev['lambda_p_square'])], key=lambda t: t[0])
    row['is_cuspidal'] = True
    row['aut_rep_type'] = 'G'
    row['related_objects'] = []
    row['atkin_lehner_eigenvals'] = []
    row['atkin_lehner_string'] = ''
    row['fricke_eigenval'] = 1
    row['multiplicity'] = 1
    if F.degree() > MAX_RING_DEGREE:
        d = F.degree()
        row.update({'dim': d, 'relative_dim': d, 'field_poly': [int(c) for c in F.defining_polynomial().list()],
                    'field_poly_is_cyclotomic': False, 'field_poly_root_of_unity': 0,
                    'field_poly_is_real_cyclotomic': False, 'hecke_ring_generator_nbound': None,
                    'hecke_ring_index': None, 'hecke_ring_index_proved': False,
                    'hecke_ring_index_factorization': None, 'field_disc': None,
                    'field_disc_factorization': None, 'nf_label': None, 'is_polredabs': None})
        return row, None
    ring, fields = ring_data(F, gens)
    row.update(fields)
    c = coords(ring, F)
    hnf = dict(ring)
    for t in HECKE_TYPES:
        hnf[t] = [c(x) for x in ev[t]]
    hnf['an'] = [c(x) if x is not None else 'NULL' for x in an]
    assert hnf['an'][0] == [1] + [0] * (F.degree() - 1), "the ring basis does not start with 1"
    hnf['ap'] = None
    hnf['maxp'] = ps[-1]
    hnf['maxp_square'] = sq[-1] if sq else None
    return row, hnf


def full_row(k, j, family, fields, hecke_orbit, cols):
    e = common_entry_values(k, j, 1, family)
    e.update(fields)
    e = entry_add_common_columns(e, {'id': None})
    e['space_label'] = make_space_label(e)
    e['hecke_orbit'] = hecke_orbit
    e['label'] = e['space_label'] + '.' + base_26(hecke_orbit)
    e['hecke_orbit_code'] = make_orbit_code(2, family, 1, k, j, 1, hecke_orbit)
    e['trace_hash'] = e['analytic_rank'] = e['qexp_display'] = None
    e['analytic_rank_proved'] = False
    e['embedded_related_objects'] = []
    return {c: nulls(e.get(c)) for c in cols}


def full_ev(k, j, family, hnf, row, cols):
    e = common_entry_values(k, j, 1, family)
    e.update(hnf)
    e['label'], e['hecke_orbit_code'] = row['label'], row['hecke_orbit_code']
    return {c: e.get(c) if c == 'an' else nulls(e.get(c)) for c in cols}


def space_plan(datadir, k, j, nf_cols, hnf_cols):
    forms = eigenforms(datadir, k, j)
    assert forms, "%d_%d: no eigenvalues" % (k, j)
    labels = {f: '2.%s.1.%d.%d.a' % (f, k, j) for f in FAMILIES}
    spaces = {f: db.smf_newspaces.lucky({'label': labels[f]}, ['label', 'new_cusp_G_dim', 'new_eis_Q_dim', 'num_forms', 'total_dim'])
              for f in FAMILIES}
    s = spaces['P']
    assert s is not None, labels['P']
    for f in FAMILIES:
        assert spaces[f] is not None and spaces[f]['new_cusp_G_dim'] == s['new_cusp_G_dim'], labels[f]
    stored = {f: list(db.smf_newforms.search({'space_label': labels[f]}, ['label', 'aut_rep_type', 'dim', 'hecke_orbit', 'trace_lambda_p']))
              for f in FAMILIES}
    for f in FAMILIES:
        assert all(r['aut_rep_type'] == 'Q' for r in stored[f]), "%s: stored forms other than Q" % labels[f]
        assert sorted(r['hecke_orbit'] for r in stored[f]) == list(range(1, len(stored[f]) + 1)), labels[f]
        assert sorted((r['dim'], r['trace_lambda_p']) for r in stored[f]) == sorted((r['dim'], r['trace_lambda_p']) for r in stored['P'])
    # match the stored Q rows
    unmatched = list(stored['P'])
    gs = []
    for F, vals in forms:
        ps, _ = computed_primes(vals)
        d = F.degree()
        tr = [trace(vals[p], F) for p in ps]
        m = [r for r in unmatched if r['dim'] == d and r['trace_lambda_p'][:len(tr)] == tr]
        assert len(m) <= 1, "%d_%d: an eigenform matches %d Q rows" % (k, j, len(m))
        if m:
            unmatched.remove(m[0])
        else:
            gs.append((F, vals))
    assert not unmatched, "%d_%d: Q rows not in the decomposition: %s" % (k, j, [r['label'] for r in unmatched])
    assert sum(F.degree() for F, _ in forms) == s['total_dim'], "%d_%d: the decomposition has dimension %d, total_dim %s" % (
        k, j, sum(F.degree() for F, _ in forms), s['total_dim'])
    gdim = sum(F.degree() for F, _ in gs)
    assert gdim == s['new_cusp_G_dim'], "%d_%d: G forms of dimension %d, new_cusp_G_dim %s" % (k, j, gdim, s['new_cusp_G_dim'])
    orbits = [g_orbit(k, j, F, vals) for F, vals in gs]
    orbits.sort(key=lambda o: sort_key(o[0]['dim'], o[0]['trace_lambda_p']))
    keys = [sort_key(o[0]['dim'], o[0]['trace_lambda_p']) for o in orbits]
    assert all(a != b for a, b in zip(keys, keys[1:])), "%d_%d: two G orbits have the same sort key" % (k, j)
    nQ = len(stored['P'])
    rows, evs, num_forms = [], [], {}
    for f in FAMILIES:
        for i, (fields, hnf) in enumerate(orbits, nQ + 1):
            row = full_row(k, j, f, fields, i, nf_cols)
            rows.append(row)
            if hnf is not None:
                evs.append(full_ev(k, j, f, hnf, row, hnf_cols))
        num_forms[labels[f]] = nQ + len(orbits)     # the decomposition is all of M_{k,j}
    info = {'space': labels['P'], 'Q': nQ, 'G orbits': [o[0]['dim'] for o in orbits],
            'primes': len(computed_primes(forms[0][1])[0]), 'squares': len(computed_primes(forms[0][1])[1]),
            'unfactored': sum(1 for o, h in orbits if h is not None and o['field_disc'] is None),
            'no ring (degree > %d)' % MAX_RING_DEGREE: sum(1 for _, h in orbits if h is None)}
    return rows, evs, num_forms, info


def main(datadir, apply=False, datafile=None, spaces=None):
    base = datafile or "smf_level1_cbs"
    nf_cols = [c for c in db.smf_newforms.search_cols if c != 'id']
    hnf_cols = [c for c in db.smf_hecke_nf.search_cols if c != 'id']
    todo = spaces or sorted(d for d in os.listdir(datadir) if re.match(r'\d+_\d+$', d))
    rows, evs, num_forms, skipped = [], [], {}, []
    for kj in todo:
        k, j = map(int, kj.split('_'))
        t0 = time.time()
        try:
            r, e, n, info = space_plan(datadir, k, j, nf_cols, hnf_cols)
        except (AssertionError, ValueError) as err:
            skipped.append((kj, repr(err)))
            print("%s: SKIPPED %r" % (kj, err), flush=True)
            continue
        rows += r
        evs += e
        num_forms.update(n)
        info['seconds'] = round(time.time() - t0)
        print(info, flush=True)
    print("%d spaces, %d new smf_newforms rows, %d new smf_hecke_nf rows, num_forms set in %d spaces; %d spaces skipped"
          % (len(todo) - len(skipped), len(rows), len(evs), len(num_forms), len(skipped)))
    with open(base + "_newforms.json", 'w') as F:
        json.dump(jsonable(rows), F)
    with open(base + "_hecke_nf.json", 'w') as F:
        json.dump(jsonable(evs), F)
    with open(base + "_num_forms.json", 'w') as F:
        json.dump(num_forms, F)
    if not apply:
        print("dry run; pass --apply to write")
        return
    assert not skipped or spaces, "some spaces fail a check; pass --spaces to apply the others"
    # delete by label to undo
    db.smf_newforms.insert_many(jsonable(rows))
    db.smf_hecke_nf.insert_many(jsonable(evs))
    for label, n in num_forms.items():
        db.smf_newspaces.update({'label': label}, {'num_forms': n}, restat=False)
    for t in (db.smf_newforms, db.smf_hecke_nf, db.smf_newspaces):
        t.stats.refresh_stats(total=False)
    print("inserted; num_forms set")


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("datadir")
    parser.add_argument("--apply", action="store_true", help="write to the database")
    parser.add_argument("--datafile", help="prefix for the output files (default: ./smf_level1_cbs)")
    parser.add_argument("--spaces", help="comma-separated k_j (default: all in DATADIR)")
    args = parser.parse_args()
    main(args.datadir, apply=args.apply, datafile=args.datafile, spaces=args.spaces.split(',') if args.spaces else None)
