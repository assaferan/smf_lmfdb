"""
Add the Hecke eigenvalues at the primes p dividing the level N of the paramodular newforms of
weight (k, j) (--weight, default 3,0), in the Roberts-Schmidt conventions (bad_primes_local.py),
with omf5's weight (a, b) = (k - 3 + j/2, j/2):

  p || N:  lambda_p = c - eps p^a, lambda_p_square = mu = -eps p^a c - p^(2a+1), with c the value
           omf5 prints;
  p^2 | N: lambda_p = T_p, lambda_p_square = T_{p^2} / 2;

and the Dirichlet coefficients a_n with n not prime to N from the Euler factors.  The columns
T(p^2, i) are NULL at p | N (the SK rows held the good-prime formulas there; those are nulled).

Sources:
  * Saito-Kurokawa lifts (type P, j = 0): the classical form, a_p(f) = -eps p^(k-2) at p || N
    and 0 at p^2 | N.  Their stored values at p | N (the printed c) are replaced;
  * type G at a level with a full omf5 run (--runs-full, -prec=100: the good primes, used to
    identify the orbit): the bad-prime sweep --sweep1 (omf5 -p=p -square at each p | N);
  * type G at the other levels: --sweep2 (omf5 at the bad primes and three good primes).
A G orbit is identified with a run form by an embedding of fields taking the run's good
eigenvalues to the stored ones (unique, or the orbit is skipped); a G orbit at a level whose
sweep has not finished is skipped.

The eigenvalues at p | N are algebraic integers in the coefficient field but in general not in
the ring generated by the good eigenvalues (p || N: type IIa, with a free unramified
parameter).  Then the Hecke ring is enlarged to the ring generated by all the eigenvalues
(bad_primes_ring.py), as for the classical forms: the basis (1 first, LLL-reduced as in
fix_hecke_ring_basis), every coordinate column, hecke_ring_generator_nbound and
hecke_ring_index_factorization change.

Writes (update_from_file files, keyed by id / label):
  PREFIX_newforms.txt:  trace_lambda_p, trace_lambda_p_square, traces, trace_display,
                        hecke_ring_generator_nbound, hecke_ring_index_factorization;
  PREFIX_hecke_nf.txt:  lambda_p, lambda_p_square, lambda_p_square_0/1/2, an and the four
                        basis columns;
  PREFIX_newspaces.txt: cusp_G_lambda_p(_square) and cusp_P_lambda_p(_square) at p | N: the sum
                        over the stored forms of the type, or NULL unless every one has a value;
and PREFIX_values.json, PREFIX_notes.json for verify_bad_primes.py.

Checks: a G value only replaces a NULL; the stored newspace sums at p prime to N are the sums
over the stored forms; the checks of bad_primes_ring.enlarge.  Run verify_bad_primes.py on the
output before --apply, and fill_trace_tables.py after it.

Usage (from the lmfdb root, with write access to the db):
    sage -python -m smf_lmfdb.db_tables.add_bad_primes --runs-full DIR --sweep1 DIR --sweep2 DIR
        --cases FILE [--weight K,J] [--types P,G] [--datafile PREFIX] [N ...]    # dry run (all levels if none)
    ... --apply
A sweep directory holds out/D.p.dat and a done.txt with lines "D p rc=0 ..." (rc=0: finished).
"""
import argparse
import ast
import json
import os
import sys
import time
import traceback
from collections import Counter

from sage.all import QQ, ZZ, PolynomialRing, NumberField, prime_range, factor, Matrix, gcd, pari, vector
from lmfdb import db
from smf_lmfdb.db_tables.bad_primes_local import local_from_omf5, local_from_sk, prime_power_coefficients
from smf_lmfdb.db_tables.bad_primes_ring import enlarge
from smf_lmfdb.db_tables.fix_sk_traces import write_update_file

PRIMES = prime_range(1000)
Qx = PolynomialRing(QQ, 'x')
Ra = PolynomialRing(QQ, 'a')
NF_COLS = ['trace_lambda_p', 'trace_lambda_p_square', 'traces', 'trace_display',
           'hecke_ring_generator_nbound', 'hecke_ring_index_factorization']
HNF_COLS = ['lambda_p', 'lambda_p_square', 'lambda_p_square_0', 'lambda_p_square_1', 'lambda_p_square_2', 'an',
            'hecke_ring_numerators', 'hecke_ring_denominators', 'hecke_ring_inverse_numerators',
            'hecke_ring_inverse_denominators']
SP_COLS = ['cusp_G_lambda_p', 'cusp_G_lambda_p_square', 'cusp_P_lambda_p', 'cusp_P_lambda_p_square']


class Sources:
    def __init__(self, runs_full, sweep1, sweep2, cases):
        self.runs_full, self.sweep1, self.sweep2 = runs_full, sweep1, sweep2
        self.cases = json.load(open(cases))
        self.done1, self.done2 = self.done_set(sweep1), self.done_set(sweep2)

    @staticmethod
    def done_set(d):
        s = set()
        fname = os.path.join(d, "done.txt")
        if os.path.exists(fname):
            for line in open(fname):
                D, p, rc = line.split()[:3]
                if rc == "rc=0":
                    s.add((int(D), int(p)))
        return s

    def case_of(self, D, p):
        k = self.cases.get("%d.%d" % (D, p))
        if k is None:                      # levels of the second sweep: classify from the valuation
            return 1 if (D // p) % p else 2
        return 1 if ("case 1" in k or "v=1," in k) else 2

    def run_forms(self, D):
        """[{cond, pos, type, poly, K, good: {q: value}, bad: {p: (printed T_p, printed T_{p^2})}}]."""
        forms = {}
        full = os.path.join(self.runs_full, "%d.dat" % D)
        if os.path.exists(full):
            data = ast.literal_eval(open(full).read())
            good = [q for q in PRIMES if D % q]
            for cond, L in data.items():
                for pos, f in enumerate(L):
                    K = field(f['field_poly'])
                    forms[(cond, pos)] = {'cond': cond, 'pos': pos, 'type': f['aut_rep_type'], 'poly': poly_of(f['field_poly']),
                                          'K': K, 'good': {q: elt(v, K) for q, v in zip(good, f['lambda_p'][:10])}, 'bad': {}}
            outdir, done = self.sweep1, self.done1
        else:
            outdir, done = self.sweep2, self.done2
        for (d, p) in sorted(done):
            if d != D:
                continue
            data = ast.literal_eval(open(os.path.join(outdir, "out", "%d.%d.dat" % (D, p))).read())
            for cond, L in data.items():
                for pos, f in enumerate(L):
                    key = (cond, pos)
                    if key not in forms:
                        forms[key] = {'cond': cond, 'pos': pos, 'type': None, 'poly': poly_of(f['field_poly']),
                                      'K': field(f['field_poly']), 'good': {}, 'bad': {}}
                    rf = forms[key]
                    assert rf['poly'] == poly_of(f['field_poly']), (D, p, key)
                    if not f['lambda_p']:
                        continue           # omf5 prints no eigenvalue for an oldform
                    if D % p:
                        rf['good'][p] = elt(f['lambda_p'][0], rf['K'])
                    else:
                        rf['bad'][p] = (f['lambda_p'][0], f['lambda_p_square'][0])
        return list(forms.values())


def poly_of(s):
    return Qx([QQ(t) for t in s.split()[1:]])


def field(s):
    P = poly_of(s)
    return None if P.degree() == 1 else NumberField(P, 'a')


def elt(s, K):
    if K is None:
        return QQ(s)
    return Ra(s.replace('^', '**'))(K.gen()) if 'a' in s else K(QQ(s))


class Ring:
    """The Hecke ring basis of an smf_hecke_nf row: elements <-> coordinates."""
    def __init__(self, h):
        poly = Qx([QQ(c) for c in h['field_poly']])
        self.K = None if poly.degree() == 1 else NumberField(poly, 'b')
        if self.K is None:
            self.B = [QQ(n[0]) / d for n, d in zip(h['hecke_ring_numerators'], h['hecke_ring_denominators'])]
        else:
            b = self.K.gen()
            self.B = [sum(QQ(c) * b**i for i, c in enumerate(n)) / d for n, d in zip(h['hecke_ring_numerators'], h['hecke_ring_denominators'])]
            self.Minv = Matrix(QQ, [list(x) for x in self.B]).inverse()

    def elt(self, c):
        if c in (None, 'NULL'):
            return None
        return sum(QQ(x) * y for x, y in zip(c, self.B))

    def coords(self, x):
        if self.K is None:
            v = [QQ(x) / self.B[0]]
        else:
            v = list((Matrix(QQ, [list(self.K(x))]) * self.Minv)[0])
        assert all(t in ZZ for t in v), ("not in the Hecke ring", x)
        return [int(t) for t in v]

    def trace(self, x):
        return QQ(x) if self.K is None else x.trace()


def find_sigma(rf, ring, target):
    """An embedding K_run -> K_db taking the run's good eigenvalues to target {q: elt}, or False."""
    qs = [q for q in target if q in rf['good']]
    if len(qs) < 3:
        return False
    if ring.K is None:
        return (lambda x: QQ(x)) if all(QQ(rf['good'][q]) == target[q] for q in qs) else False
    if rf['K'] is None or rf['K'].degree() != ring.K.degree():
        return False
    # the embedding is determined by the image of a good lambda_q generating K_run: write the
    # generator of K_run as a polynomial in it (linear algebra; listing the embeddings means
    # factoring over K, which takes hours in degree 15-16)
    K0, d = rf['K'], rf['K'].degree()
    for q in qs:
        x = rf['good'][q]
        M = Matrix(QQ, [list(x**i) for i in range(d)])
        if M.rank() < d:
            continue
        g = vector(QQ, [0, 1] + [0] * (d - 2)) * M.inverse()
        img = sum(c * target[q]**i for i, c in enumerate(g))
        if K0.polynomial()(img) != 0:
            return False
        s = K0.hom([img], ring.K)
        return s if all(s(rf['good'][q2]) == target[q2] for q2 in qs) else False
    for s in K0.embeddings(ring.K):
        if all(s(rf['good'][q]) == target[q] for q in qs):
            return s
    return False


def convert_level(src, D, out, stats, notes, current, weight=(3, 0), types=('P', 'G')):
    k, j = weight
    a = k - 3 + j // 2
    forms = list(db.smf_newforms.search({'space_label': '2.K.%d.%d.%d.a' % (D, k, j)},
                                        ['id', 'label', 'dim', 'aut_rep_type', 'hecke_orbit_code', 'atkin_lehner_eigenvals',
                                         'related_objects'] + NF_COLS))
    hnf = {h['hecke_orbit_code']: h for h in db.smf_hecke_nf.search(
        {'hecke_orbit_code': {'$in': [f['hecke_orbit_code'] for f in forms]}},
        ['id', 'label', 'hecke_orbit_code', 'field_poly'] + HNF_COLS)}
    bad_ps = [p for p in PRIMES if D % p == 0]
    runs = None
    used = Counter()
    for f in forms:
        if f['aut_rep_type'] not in types:
            continue
        current[0] = f['label']
        eps = dict(f['atkin_lehner_eigenvals'])
        h = hnf.get(f['hecke_orbit_code'])
        ring = Ring(h) if h else None
        local = {}
        if f['aut_rep_type'] == 'P':
            for p in bad_ps:
                case = src.case_of(D, p)
                local[p] = local_from_sk(case, p, eps[p], QQ(-eps[p] * p**(k - 2)) if case == 1 else QQ(0), k=k)
            how = 'classical'
        elif f['aut_rep_type'] == 'G':
            if runs is None:
                runs = src.run_forms(D)
            missing = [p for p in bad_ps if not any(p in rf['bad'] for rf in runs)]
            if missing:
                stats['G orbit: sweep not finished at its level'] += 1
                continue
            if ring is not None:
                target = {q: ring.elt(h['lambda_p'][PRIMES.index(q)]) for q in PRIMES[:25] if D % q}
                hits = []
                for rf in runs:
                    if rf['poly'].degree() != f['dim'] or not rf['bad']:
                        continue
                    qs = [q for q in list(rf['good'])[:3] if q in target]
                    if [ring.trace(target[q]) for q in qs] != [rf['good'][q] if rf['K'] is None else rf['good'][q].trace() for q in qs]:
                        continue
                    s = find_sigma(rf, ring, target)
                    if s is not False:
                        hits.append((rf, s))
                if len({(rf['cond'], rf['pos']) for rf, _ in hits}) != 1:
                    stats['G orbit: not mapped uniquely (%d)' % len(hits)] += 1
                    notes.append(('not mapped', f['label'], len(hits)))
                    continue
                rf, to_db = hits[0]
            else:
                # degree > 20: by the traces at the good primes
                tl = f['trace_lambda_p']
                hits = [rf for rf in runs if rf['poly'].degree() == f['dim'] and rf['bad'] and len(rf['good']) >= 3 and
                        all((rf['good'][q] if rf['K'] is None else rf['good'][q].trace()) == tl[PRIMES.index(q)] for q in rf['good'])]
                if len(hits) != 1:
                    stats['G orbit of degree > 20: not mapped uniquely (%d)' % len(hits)] += 1
                    continue
                rf, to_db = hits[0], (lambda x: x)
            used[(rf['cond'], rf['pos'])] += 1
            for p in bad_ps:
                tp, tp2 = rf['bad'][p]
                K = rf['K']
                if src.case_of(D, p) == 1:
                    local[p] = local_from_omf5(1, p, eps[p], c=to_db(elt(tp, K)), a=a)
                else:
                    local[p] = local_from_omf5(2, p, eps[p], Tp=to_db(elt(tp, K)), Tp2=to_db(elt(tp2, K)), a=a)
            how = 'omf5'
        else:
            stats['type %s skipped' % f['aut_rep_type']] += 1
            continue
        dim = f['dim']

        def tr(x):
            # the trace over the orbit: dim * x for a rational x
            if x in QQ:
                return dim * QQ(x)
            return x.trace()
        nf_new = {'id': f['id'], 'trace_lambda_p': list(f['trace_lambda_p']),
                  'trace_lambda_p_square': list(f['trace_lambda_p_square'] or []), 'traces': list(f['traces'] or []),
                  'hecke_ring_generator_nbound': f.get('hecke_ring_generator_nbound'),
                  'hecke_ring_index_factorization': f.get('hecke_ring_index_factorization')}
        h_new = {'id': h['id'], 'lambda_p': list(h['lambda_p']), 'lambda_p_square': list(h['lambda_p_square'] or []),
                 'an': list(h['an'])} if h else None
        outside = False
        for p, (lam, mu, fac) in local.items():
            i = PRIMES.index(p)
            for col, val in (('trace_lambda_p', lam), ('trace_lambda_p_square', mu)):
                if i < len(nf_new[col]):
                    old = nf_new[col][i]
                    if f['aut_rep_type'] == 'G' and old is not None:
                        notes.append(('G value not NULL', f['label'], col, p, old))
                        stats['G: overwrote a stored value'] += 1
                    nf_new[col][i] = int(tr(val))
            if h_new:
                for col, val in (('lambda_p', lam), ('lambda_p_square', mu)):
                    if i < len(h_new[col]):
                        old = h_new[col][i]
                        if f['aut_rep_type'] == 'G' and old not in (None, 'NULL'):
                            notes.append(('G hecke value not NULL', f['label'], col, p, old))
                            stats['G: overwrote a stored value'] += 1
                        try:
                            h_new[col][i] = ring.coords(val)
                        except AssertionError:
                            outside = True
                            h_new[col][i] = None
        # Dirichlet coefficients at the n not prime to N
        an_el = {}
        if h_new:
            ppc = {p: prime_power_coefficients(local[p][2], 12) for p in local}
            for n in range(1, len(h_new['an']) + 1):
                if gcd(n, D) == 1:
                    continue
                m, val = n, 1
                for p, e in factor(n):
                    if D % p == 0:
                        val *= ppc[p][e]
                        m //= p**e
                am = 1 if m == 1 else ring.elt(h['an'][m - 1])
                if am is None:
                    stats['an: cofactor missing'] += 1
                    continue
                x = am * val
                try:
                    h_new['an'][n - 1] = ring.coords(x)
                except AssertionError:
                    outside = True
                    h_new['an'][n - 1] = None
                an_el[n] = x
            for n, x in an_el.items():
                if n <= len(nf_new['traces']):
                    nf_new['traces'][n - 1] = int(tr(x))
            if f['dim'] == 1:
                # rational: the traces beyond len(an) too
                for n in range(len(h_new['an']) + 1, len(nf_new['traces']) + 1):
                    if gcd(n, D) == 1 or nf_new['traces'][n - 1] is not None:
                        continue
                    m, val = n, QQ(1)
                    for p, e in factor(n):
                        if D % p == 0:
                            val *= ppc[p][e]
                            m //= p**e
                    am = 1 if m == 1 else nf_new['traces'][m - 1]
                    if am is not None:
                        nf_new['traces'][n - 1] = int(am * val)
        nf_new['trace_display'] = nf_new['trace_lambda_p'][:4]
        out['newforms'][f['label']] = nf_new
        if h_new and outside:
            new, nf_ring, info = enlarge(D, f, h, ring, {p: local[p][:2] for p in local}, an_el, weight)
            new['id'] = h['id']
            for col in HNF_COLS:
                new.setdefault(col, h.get(col))          # columns that are NULL stay NULL
            out['hecke_nf'][h['label']] = new
            nf_new.update(nf_ring)
            out['ring_changes'][f['label']] = info
            stats['Hecke ring enlarged by the bad primes'] += 1
            notes.append(('ring enlarged', f['label'], f['dim'], info))
        elif h_new:
            for col in ('lambda_p_square_0', 'lambda_p_square_1', 'lambda_p_square_2', 'hecke_ring_numerators',
                        'hecke_ring_denominators', 'hecke_ring_inverse_numerators', 'hecke_ring_inverse_denominators'):
                h_new[col] = h.get(col)
            out['hecke_nf'][h['label']] = h_new
        if h_new:
            # T(p^2, i) is the classical double coset at a good p only: NULL at p | N.  The SK rows
            # held the good-prime formulas evaluated at p | N; nulled (decision 2026-11-21)
            row = out['hecke_nf'][h['label']]
            for col in ('lambda_p_square_0', 'lambda_p_square_1', 'lambda_p_square_2'):
                if row.get(col) is None:
                    continue
                row[col] = list(row[col])
                for p in bad_ps:
                    i = PRIMES.index(p)
                    if i < len(row[col]) and row[col][i] not in (None, 'NULL'):
                        row[col][i] = 'NULL'
                        stats['T(p^2,i) at p | N nulled (%s)' % f['aut_rep_type']] += 1
        stats[(f['aut_rep_type'], how, 'with hecke_nf' if h else 'traces only')] += 1
    if any(n > 1 for n in used.values()):
        stats['G: run form used twice'] += 1
        notes.append(('run form used twice', D, [k for k, n in used.items() if n > 1]))


def newspace_sums(D, out, stats, notes, weight=(3, 0)):
    """The smf_newspaces row of level D with the G and P sums at p | N recomputed, or None."""
    sp = '2.K.%d.%d.%d.a' % (D, weight[0], weight[1])
    s = db.smf_newspaces.lucky({'label': sp}, ['label'] + SP_COLS)
    if s is None:
        return None
    forms = list(db.smf_newforms.search({'space_label': sp, 'aut_rep_type': {'$in': ['G', 'P']}},
                                        ['label', 'aut_rep_type', 'trace_lambda_p', 'trace_lambda_p_square']))

    def value(f, fcol, i):
        v = f.get(fcol) or []
        return v[i] if i < len(v) else None
    # good p: the stored sums must be the sums over the stored forms, or the space is left alone
    for t in ('G', 'P'):
        fs = [f for f in forms if f['aut_rep_type'] == t]
        for col, fcol in (('cusp_%s_lambda_p' % t, 'trace_lambda_p'), ('cusp_%s_lambda_p_square' % t, 'trace_lambda_p_square')):
            for i, x in enumerate(s.get(col) or []):
                vals = [value(f, fcol, i) for f in fs]
                if D % PRIMES[i] and x is not None and all(v is not None for v in vals) and x != sum(vals):
                    stats['newspace: stored good sum is not the sum over its forms (left alone)'] += 1
                    notes.append(('newspace sum mismatch', sp, col, PRIMES[i], x, sum(vals)))
                    return None
    changed = False
    for t in ('G', 'P'):
        fs = [f for f in forms if f['aut_rep_type'] == t]
        for col, fcol in (('cusp_%s_lambda_p' % t, 'trace_lambda_p'), ('cusp_%s_lambda_p_square' % t, 'trace_lambda_p_square')):
            stored = s.get(col)
            if stored is None:
                continue
            stored = list(stored)
            for i in range(len(stored)):
                p = PRIMES[i]
                old_vals = [value(f, fcol, i) for f in fs]
                if D % p:
                    continue
                vals = [out['newforms'][f['label']][fcol][i] if f['label'] in out['newforms'] and i < len(out['newforms'][f['label']][fcol])
                        else v for f, v in zip(fs, old_vals)]
                new = sum(vals) if all(v is not None for v in vals) else None
                if new != stored[i]:
                    stored[i] = new
                    changed = True
                    stats['newspace sum at p | N changed (%s)' % t] += 1
            s[col] = stored
    return s if changed else None


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--runs-full", required=True)
    parser.add_argument("--sweep1", required=True)
    parser.add_argument("--sweep2", required=True)
    parser.add_argument("--cases", required=True)
    parser.add_argument("--datafile", default="smf_bad_primes")
    parser.add_argument("--weight", default="3,0", help="the paramodular weight k,j")
    parser.add_argument("--types", default="P,G",
                        help="the types to convert; G alone leaves the P orbits of a level whose sweep finished"
                             " after an earlier --apply as they are (that conversion is not idempotent)")
    parser.add_argument("--apply", action="store_true")
    parser.add_argument("levels", nargs="*", type=int)
    args = parser.parse_args()
    pari.allocatemem(16 * 10**9, silent=True)
    src = Sources(args.runs_full, args.sweep1, args.sweep2, args.cases)
    weight = tuple(int(x) for x in args.weight.split(","))
    levels = args.levels or sorted({r for r in db.smf_newforms.search({'family': 'K', 'weight': list(weight), 'level': {'$gt': 1}}, 'level')})
    out = {'newforms': {}, 'hecke_nf': {}, 'ring_changes': {}}
    stats, notes, current = Counter(), [], [None]
    for D in levels:
        t0 = time.time()
        try:
            convert_level(src, D, out, stats, notes, current, weight, tuple(args.types.split(",")))
        except Exception as e:
            stats['level failed'] += 1
            notes.append(('level failed', D, current[0], '%s: %s' % (type(e).__name__, str(e)[:120]),
                          traceback.format_exc().splitlines()[-4:-1]))
        print("level %d: %.1fs" % (D, time.time() - t0), file=sys.stderr, flush=True)
    sp_rows = [s for s in (newspace_sums(D, out, stats, notes, weight) for D in levels) if s is not None]
    out['newspaces'] = {s['label']: s for s in sp_rows}
    print(dict(stats), flush=True)
    for x in notes[:20]:
        print("  ", x)
    base = args.datafile
    json.dump(out, open(base + "_values.json", "w"), default=lambda o: int(o) if o in ZZ else str(o))
    json.dump(notes, open(base + "_notes.json", "w"), default=str)
    print("orbits with new values: %d smf_newforms, %d smf_hecke_nf (%d rings enlarged); %d smf_newspaces"
          % (len(out['newforms']), len(out['hecke_nf']), len(out['ring_changes']), len(sp_rows)))
    if stats['level failed']:
        print("some levels failed: not writing update files")
        sys.exit(1)
    nf_file, hnf_file, sp_file = base + "_newforms.txt", base + "_hecke_nf.txt", base + "_newspaces.txt"
    write_update_file(nf_file, db.smf_newforms, 'id', list(out['newforms'].values()), NF_COLS)
    write_update_file(hnf_file, db.smf_hecke_nf, 'id', list(out['hecke_nf'].values()), HNF_COLS)
    write_update_file(sp_file, db.smf_newspaces, 'label', sp_rows, SP_COLS)
    if not args.apply:
        print("dry run; check with verify_bad_primes.py, then pass --apply to write")
        return
    # update_from_file builds replacement tables (undo with reload_revert())
    db.smf_newforms.update_from_file(nf_file, label_col='id')
    db.smf_hecke_nf.update_from_file(hnf_file, label_col='id')
    db.smf_newspaces.update_from_file(sp_file, label_col='label')
    print("updated; now run fill_trace_tables.py")


