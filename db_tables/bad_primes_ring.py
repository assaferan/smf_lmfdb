"""
Enlarge the Hecke ring of a paramodular orbit whose eigenvalues at the bad primes are not in its stored ring
(the ring is generated by the eigenvalues at all primes, as for the classical forms).

  H_new = the order generated by H_old (generated by the good lambda_p and T(p,2)) and, at each
          p | N, lambda_p and mu_p = lambda_p_square (Roberts-Schmidt).
  index_new = index_old / [H_new : H_old].
  nbound: the smallest n such that the lambda_j, j <= n, generate H_new, with lambda_j = lambda_p
          for j = p and lambda_p_square for j = p^2, as before (good p^2: omf5's T(p,2), as in
          omf5_data's recompute_hecke_rings.py), now with the bad primes included.
  basis:  reduced_basis of fix_hecke_ring_basis (1 first, LLL against lambda_p), with lambda_p
          the full column (bad primes included), so that fix_hecke_ring_basis leaves it as it is.

Checks: the old nbound and index are reproduced from the omf5_data generators without the bad
primes; every coordinate is integral in the new basis; a_1 = (1, 0, ..., 0); each new coordinate
gives back the same field element.
"""
import ast, os, re
from sage.all import Matrix, QQ, ZZ, vector, lcm, factor, prime_range, prod
from smf_lmfdb.db_tables.fix_hecke_ring_basis import reduced_basis

# the omf5_data submodule, found from this file (not the working directory)
OMF5 = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                    "Hecke_Eigenvalues", "paramodular", "omf5_data", "hecke_evs_3_0", "data", "hecke_ev_3_0_%d.dat")
PS100 = prime_range(100)
_cache = {}


def omf5_entries(D):
    if D not in _cache:
        _cache[D] = ast.literal_eval(re.sub(r'(\d)L', r'\1', open(OMF5 % D).read()))     # raises if missing
    return _cache[D]


def zspan(vs):
    """HNF rows (over QQ) of the Z-span of the rational vectors vs."""
    M = Matrix(QQ, vs)
    den = lcm([c.denominator() for c in M.list()] + [1])
    H = (M * den).change_ring(ZZ).echelon_form()
    return [r / den for r in H.rows() if r]


def closure(vs, mult):
    M = zspan(vs)
    while True:
        new = zspan([mult(u, v) for i, u in enumerate(M) for v in M[i:]] + M)
        if new == M:
            return M
        M = new


def vol(M):
    return abs(Matrix(QQ, M).det())


def enlarge(D, f, h, ring, local, an_el):
    """New smf_hecke_nf coordinate/basis columns and smf_newforms ring columns, or raise."""
    K = ring.K
    d = K.degree()
    Bm = Matrix(QQ, [list(K(b)) for b in ring.B])          # stored basis, power-basis rows
    Bi = Bm.inverse()
    cB = lambda x: vector(QQ, list(K(x))) * Bi                # coordinates in the stored basis
    eB = lambda v: sum(QQ(c) * b for c, b in zip(v, ring.B))
    mult = lambda u, v: cB(eB(u) * eB(v))
    one = cB(K(1))
    bad = sorted(local)
    # the generators in omf5_data's convention, matched by field polynomial and the good lambda_p
    good_lam = {q: ring.elt(h['lambda_p'][i]) for i, q in enumerate(PS100) if D % q and i < len(h['lambda_p'])}
    cands = []
    for e in omf5_entries(D):
        if [int(c) for c in e['field_poly']] != [int(c) for c in h['field_poly']]:
            continue
        a = K.gen()
        Bo = [sum(QQ(n) * a**i for i, n in enumerate(nums)) / den for nums, den in zip(e['hecke_ring_numerators'], e['hecke_ring_denominators'])]
        el = lambda v: None if v == 'NULL' else sum(QQ(c) * b for c, b in zip(v, Bo))
        lp = {q: el(v) for q, v in zip(PS100, e['lambda_p']) if D % q}
        if all(lp.get(q) == good_lam[q] for q in good_lam if lp.get(q) is not None) and sum(1 for q in good_lam if lp.get(q) is not None) >= 3:
            cands.append((e, el))
    assert len(cands) == 1, ("omf5_data entry not unique", f['label'], len(cands))
    e, el = cands[0]
    lamj = sorted([(q, cB(el(v))) for q, v in zip(PS100, e['lambda_p']) if v != 'NULL' and D % q] +
                  [(q * q, cB(el(v))) for q, v in zip(PS100, e['lambda_p_square']) if v != 'NULL' and D % q], key=lambda t: t[0])
    # check: the good generators give the stored ring, and the stored nbound
    H_old = closure([one] + [v for _, v in lamj], mult)
    assert vol(H_old) == 1, ("good generators do not give the stored ring", f['label'], vol(H_old))
    nb, M = 1, [one]
    for j, v in lamj:
        if len(M) == d and vol(M) == 1:
            break
        M = closure(M + [v], mult); nb = j
    assert nb == f['hecke_ring_generator_nbound'], ("old nbound not reproduced", f['label'], nb, f['hecke_ring_generator_nbound'])
    # the enlarged ring
    gens = sorted(lamj + [(p, cB(local[p][0])) for p in bad] + [(p * p, cB(local[p][1])) for p in bad], key=lambda t: t[0])
    H = closure([one] + [v for _, v in gens], mult)
    assert len(H) == d
    rel = 1 / vol(H)                                          # [H_new : H_old]
    assert rel in ZZ and rel > 1, (f['label'], rel)
    nb, M = 1, [one]
    for j, v in gens:
        if len(M) == d and vol(M) == vol(H):
            break
        M = closure(M + [v], mult); nb = j
    assert len(M) == d and vol(M) == vol(H)
    old_index = prod([ZZ(p) ** e_ for p, e_ in f["hecke_ring_index_factorization"]]) if f['hecke_ring_index_factorization'] else ZZ(1)
    new_index = old_index / rel
    assert new_index in ZZ, (f['label'], old_index, rel)
    # the basis: 1 first, LLL against the full lambda_p column
    PS = prime_range(1000)
    def lam_el(i):
        p = PS[i]
        return local[p][0] if p in local else ring.elt(h['lambda_p'][i])
    def sq_el(i):
        p = PS[i]
        return local[p][1] if p in local else ring.elt(h['lambda_p_square'][i])
    lam_all = [lam_el(i) for i in range(len(h['lambda_p']))]
    Hpow = Matrix(QQ, [list(eB(r)) for r in H])
    T = reduced_basis(Hpow, [vector(QQ, list(K(x))) for x in lam_all if x is not None])
    Ti = T.inverse()
    def co(x):
        if x is None:
            return 'NULL'
        w = vector(QQ, list(K(x))) * Ti
        assert all(c in ZZ for c in w), ("not in the enlarged ring", f['label'], x)
        assert sum(c * K(list(r)) for c, r in zip(w, T.rows())) == K(x)
        return [int(c) for c in w]
    new = {'lambda_p': [co(x) for x in lam_all]}
    if h.get('lambda_p_square') is not None:
        new['lambda_p_square'] = [co(sq_el(i)) for i in range(len(h['lambda_p_square']))]
    for col in ('lambda_p_square_0', 'lambda_p_square_1', 'lambda_p_square_2'):
        if h.get(col) is not None:
            new[col] = [co(ring.elt(v)) for v in h[col]]          # T(p^2, i): NULL at the bad p, as decided
    an_all = [an_el[n] if n in an_el else ring.elt(h['an'][n - 1]) for n in range(1, len(h['an']) + 1)]
    new['an'] = [co(x) for x in an_all]
    assert new['an'][0] == [1] + [0] * (d - 1)
    dens = [int(r.denominator()) for r in T.rows()]
    new['hecke_ring_numerators'] = [[int(c * den) for c in r] for r, den in zip(T.rows(), dens)]
    new['hecke_ring_denominators'] = dens
    idens = [int(r.denominator()) for r in Ti.rows()]
    new['hecke_ring_inverse_numerators'] = [[int(c * den) for c in r] for r, den in zip(Ti.rows(), idens)]
    new['hecke_ring_inverse_denominators'] = idens
    nf = {'hecke_ring_generator_nbound': int(nb),
          'hecke_ring_index_factorization': [[int(p), int(e_)] for p, e_ in factor(new_index)] if new_index > 1 else []}
    info = {'rel': int(rel), 'old_index': int(old_index), 'new_index': int(new_index), 'old_nbound': f['hecke_ring_generator_nbound'], 'nbound': int(nb)}
    return new, nf, info
